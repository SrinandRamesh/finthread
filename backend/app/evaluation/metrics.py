"""Evaluation metrics (Member 3). Contract Section 8.

Transaction-level evaluation of graph detection vs the rule-based baseline.
Rows with a blank label are excluded. Positive = label == "suspicious".
Graph prediction = transaction belongs to an alerted cluster.
Metrics are computed live on every run; nothing is hardcoded.
"""
from __future__ import annotations

from typing import Any, Iterable, Optional

import pandas as pd

from app.contracts import TYPOLOGY_LABELS, BaselineOutput, EvaluationResult, ScoredCluster
from app.intelligence.risk import cfg_value
from app.intelligence.typology import SEVERITY_ORDER


def _div(a: float, b: float) -> float:
    return a / b if b else 0.0


def confusion(actual: Iterable[bool], predicted: Iterable[bool]) -> dict[str, int]:
    tp = fp = fn = tn = 0
    for a, p in zip(actual, predicted):
        if a and p:
            tp += 1
        elif p:
            fp += 1
        elif a:
            fn += 1
        else:
            tn += 1
    return {"tp": tp, "fp": fp, "fn": fn, "tn": tn}


def scores(cm: dict[str, int]) -> dict[str, float]:
    tp, fp, fn, tn = cm["tp"], cm["fp"], cm["fn"], cm["tn"]
    precision = _div(tp, tp + fp)
    recall = _div(tp, tp + fn)
    f1 = _div(2 * precision * recall, precision + recall)
    accuracy = _div(tp + tn, tp + fp + fn + tn)
    return {k: round(v, 4) for k, v in
            {"precision": precision, "recall": recall, "f1": f1, "accuracy": accuracy}.items()}


def _model(name: str, display: str, actual: list[bool], predicted: list[bool]) -> dict[str, Any]:
    cm = confusion(actual, predicted)
    return {"model": name, "display_name": display, **scores(cm),
            "flagged_count": int(sum(predicted)), "confusion_matrix": cm}


def _notes(graph: dict, base: dict, label_source: Optional[str]) -> list[str]:
    notes = []
    if label_source == "synthetic":
        notes.append("Labels come from a synthetic dataset generated by backend/scripts/generate_synthetic.py "
                     "(seed 42). Results describe this dataset only.")
    elif label_source == "uploaded":
        notes.append("Labels come from the uploaded dataset's 'label' column.")
    g, b = graph, base
    notes.append(
        f"Graph-based detection: precision {g['precision']:.2f}, recall {g['recall']:.2f}, F1 {g['f1']:.2f} "
        f"({g['confusion_matrix']['tp']} true positives, {g['confusion_matrix']['fp']} false positives, "
        f"{g['confusion_matrix']['fn']} missed)."
    )
    notes.append(
        f"Rule-based baseline: precision {b['precision']:.2f}, recall {b['recall']:.2f}, F1 {b['f1']:.2f} "
        f"({b['confusion_matrix']['tp']} true positives, {b['confusion_matrix']['fp']} false positives, "
        f"{b['confusion_matrix']['fn']} missed)."
    )
    if g["f1"] > b["f1"]:
        notes.append(f"On this dataset graph detection has the higher F1 ({g['f1']:.2f} vs {b['f1']:.2f}).")
    elif b["f1"] > g["f1"]:
        notes.append(f"On this dataset the baseline has the higher F1 ({b['f1']:.2f} vs {g['f1']:.2f}).")
    else:
        notes.append("Both approaches have the same F1 on this dataset.")
    return notes


def evaluate(transactions: pd.DataFrame, clusters: list[ScoredCluster],
             baseline: BaselineOutput, cfg: Any, label_source: Optional[str] = None) -> EvaluationResult:
    thresholds = {
        k: float(cfg_value(cfg, k, d)) for k, d in (
            ("ALERT_THRESHOLD", 40), ("BASELINE_LARGE_TX", 1_000_000),
            ("BASELINE_DAILY_OUT_AMOUNT", 2_500_000), ("BASELINE_DAILY_OUT_COUNT", 10))
    }
    if transactions is None or transactions.empty or "label" not in transactions.columns:
        return {"available": False, "reason": "No labelled transactions in the active dataset.",
                "thresholds": thresholds}

    lab = transactions["label"].astype("string").str.strip().str.lower()
    mask = lab.isin(["suspicious", "normal"])
    df = transactions[mask].copy()
    if df.empty:
        return {"available": False, "reason": "No labelled transactions in the active dataset.",
                "thresholds": thresholds}

    graph_ids = {t for c in clusters if c.alerted for t in c.transaction_ids}
    base_ids = baseline.flagged_transaction_ids
    ids = df["transaction_id"].astype(str).tolist()
    actual = (lab[mask] == "suspicious").tolist()
    g_pred = [t in graph_ids for t in ids]
    b_pred = [t in base_ids for t in ids]

    graph = _model("graph", "Graph-based detection", actual, g_pred)
    base = _model("baseline", "Rule-based baseline", actual, b_pred)

    per_typology = []
    if "gt_typology" in df.columns:
        gt = df["gt_typology"].astype("string").str.strip().str.upper()
        for t in SEVERITY_ORDER:
            sel = (gt == t).fillna(False).tolist()
            pos_ids = [i for i, s in zip(ids, sel) if s]
            if not pos_ids:
                continue
            per_typology.append({
                "typology": t, "label": TYPOLOGY_LABELS[t], "positives": len(pos_ids),
                "graph_recall": round(_div(sum(i in graph_ids for i in pos_ids), len(pos_ids)), 4),
                "baseline_recall": round(_div(sum(i in base_ids for i in pos_ids), len(pos_ids)), 4),
            })

    positives = int(sum(actual))
    return {
        "available": True,
        "reason": None,
        "granularity": "transaction",
        "label_source": label_source,
        "total": len(ids),
        "positives": positives,
        "negatives": len(ids) - positives,
        "thresholds": thresholds,
        "models": [graph, base],
        "per_typology": per_typology,
        "notes": _notes(graph, base, label_source),
    }
