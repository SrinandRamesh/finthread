"""Intelligence routes (Member 3): overview, clusters, cluster detail, alerts, evaluation.
Contract Section 10, endpoints 11-15."""
from __future__ import annotations

from collections import Counter
from typing import Optional

from fastapi import APIRouter, HTTPException, Query

from app import schemas
from app.contracts import TYPOLOGY_LABELS, AnalysisResult, ScoredCluster
from app.graph.serialize import build_graph_out, to_pattern_out, to_transaction_out
from app.intelligence.typology import SEVERITY_ORDER
from app.state import get_current_result

router = APIRouter(tags=["intel"])

NO_RUN = "No analysis run yet. Upload a dataset or load the sample."
SYNTHETIC_NOTE = ("Labels come from a synthetic dataset generated by backend/scripts/generate_synthetic.py "
                  "(seed 42). Results describe this dataset only.")


def _require() -> AnalysisResult:
    result = get_current_result()
    if result is None:
        raise HTTPException(status_code=409, detail=NO_RUN)
    return result


def _dataset_info(r: AnalysisResult) -> schemas.DatasetInfo:
    d = r.dataset
    return schemas.DatasetInfo(dataset_id=d.dataset_id, name=d.name, source=d.source,
                               uploaded_at=d.uploaded_at, row_count=d.row_count, has_labels=d.has_labels)


def _run_summary(r: AnalysisResult) -> schemas.RunSummary:
    return schemas.RunSummary(
        run_id=r.run_id, dataset_id=r.dataset.dataset_id, status="completed",
        started_at=r.started_at, finished_at=r.finished_at,
        duration_ms=max(0, int((r.finished_at - r.started_at).total_seconds() * 1000)),
        counts=schemas.RunCounts(
            transactions=len(r.detection.transactions),
            accounts=r.detection.graph.number_of_nodes(),
            patterns=len(r.detection.patterns),
            clusters=len(r.clusters),
            alerts=len(r.alerts),
        ),
    )


def _summary(c: ScoredCluster) -> schemas.ClusterSummary:
    return schemas.ClusterSummary(
        cluster_id=c.cluster_id, risk_score=c.risk_score, risk_level=c.risk_level,
        primary_typology=c.primary_typology, typologies=list(c.typologies),
        account_count=len(c.accounts), transaction_count=len(c.transaction_ids),
        total_amount=c.total_amount, start_time=c.start_time, end_time=c.end_time,
        median_hop_minutes=c.median_hop_minutes, alerted=c.alerted, headline=c.explanation.headline,
    )


def _alert_out(a) -> schemas.AlertOut:
    return schemas.AlertOut(
        alert_id=a.alert_id, cluster_id=a.cluster_id, risk_score=a.risk_score, risk_level=a.risk_level,
        primary_typology=a.primary_typology, typologies=list(a.typologies), headline=a.headline,
        created_at=a.created_at, account_count=a.account_count, transaction_count=a.transaction_count,
        total_amount=a.total_amount, status="open",
    )


def _evaluation(r: AnalysisResult) -> schemas.EvaluationOut:
    ev = dict(r.evaluation or {})
    if not ev.get("available"):
        return schemas.EvaluationOut(available=False, reason=ev.get("reason") or "Evaluation not available.",
                                     thresholds=ev.get("thresholds", {}))
    if not ev.get("label_source"):
        ev["label_source"] = "synthetic" if r.dataset.source == "sample" else "uploaded"
    notes = list(ev.get("notes", []))
    if ev["label_source"] == "synthetic" and not any("synthetic" in n for n in notes):
        notes.insert(0, SYNTHETIC_NOTE)
    ev["notes"] = notes
    return schemas.EvaluationOut(**ev)


