@router.get("/overview", response_model=schemas.OverviewOut)
def overview() -> schemas.OverviewOut:
    r = _require()
    df = r.detection.transactions
    graph_ids = {t for c in r.clusters if c.alerted for t in c.transaction_ids}

    typ_counter: Counter = Counter(t for c in r.clusters for t in c.typologies)
    typology_counts = [schemas.TypologyCount(typology=t, label=TYPOLOGY_LABELS[t], count=typ_counter[t])
                       for t in SEVERITY_ORDER if typ_counter[t]]
    lvl = Counter(c.risk_level for c in r.clusters)
    risk_distribution = [schemas.LevelCount(level=l, count=lvl.get(l, 0)) for l in ("high", "medium", "low")]

    daily = []
    if not df.empty:
        d = df[["transaction_id", "amount", "timestamp"]].copy()
        d["date"] = d["timestamp"].dt.strftime("%Y-%m-%d")
        d["flag_amt"] = d["amount"].where(d["transaction_id"].astype(str).isin(graph_ids), 0.0)
        g = d.groupby("date").agg(tx_count=("transaction_id", "count"), total_amount=("amount", "sum"),
                                  flagged_amount=("flag_amt", "sum")).reset_index()
        daily = [schemas.DailyVolume(date=row.date, tx_count=int(row.tx_count),
                                     total_amount=round(float(row.total_amount), 2),
                                     flagged_amount=round(float(row.flagged_amount), 2))
                 for row in g.itertuples(index=False)]

    headline = None
    ev = r.evaluation or {}
    if ev.get("available"):
        m = {x["model"]: x for x in ev["models"]}
        headline = schemas.HeadlineMetrics(graph_f1=m["graph"]["f1"], baseline_f1=m["baseline"]["f1"],
                                           graph_recall=m["graph"]["recall"], baseline_recall=m["baseline"]["recall"])

    stats = schemas.OverviewStats(
        total_transactions=len(df),
        total_accounts=r.detection.graph.number_of_nodes(),
        total_amount=round(float(df["amount"].sum()), 2) if not df.empty else 0.0,
        flagged_transactions=len(graph_ids),
        clusters=len(r.clusters),
        alerts=len(r.alerts),
        high_risk_alerts=sum(1 for a in r.alerts if a.risk_level == "high"),
        medium_risk_alerts=sum(1 for a in r.alerts if a.risk_level == "medium"),
    )
    return schemas.OverviewOut(
        dataset=_dataset_info(r), run=_run_summary(r), stats=stats,
        typology_counts=typology_counts, risk_distribution=risk_distribution,
        top_alerts=[_alert_out(a) for a in r.alerts[:5]], daily_volume=daily, headline_metrics=headline,
    )


@router.get("/clusters", response_model=schemas.ClusterList)
def clusters(
    min_risk: Optional[int] = Query(None, ge=0, le=100),
    typology: Optional[str] = None,
    alerted_only: bool = False,
    sort: str = Query("-risk_score", pattern=r"^(-risk_score|-total_amount|start_time)$"),
) -> schemas.ClusterList:
    r = _require()
    items = list(r.clusters)
    if min_risk is not None:
        items = [c for c in items if c.risk_score >= min_risk]
    if typology:
        items = [c for c in items if typology.upper() in c.typologies]
    if alerted_only:
        items = [c for c in items if c.alerted]
    if sort == "-total_amount":
        items.sort(key=lambda c: (-c.total_amount, c.cluster_id))
    elif sort == "start_time":
        items.sort(key=lambda c: (c.start_time, c.cluster_id))
    else:
        items.sort(key=lambda c: (-c.risk_score, -c.total_amount, c.cluster_id))
    return schemas.ClusterList(items=[_summary(c) for c in items], total=len(items))


@router.get("/clusters/{cluster_id}", response_model=schemas.ClusterDetail)
def cluster_detail(cluster_id: str) -> schemas.ClusterDetail:
    r = _require()
    c = next((x for x in r.clusters if x.cluster_id == cluster_id), None)
    if c is None:
        raise HTTPException(status_code=404, detail=f"Cluster {cluster_id} not found")

    hits = {h.pattern_id: h for h in r.detection.patterns}
    df = r.detection.transactions
    ids = set(c.transaction_ids)
    sub = df[df["transaction_id"].astype(str).isin(ids)].sort_values("timestamp")
    accounts = {a.account_id for a in c.accounts}
    e = c.explanation

    return schemas.ClusterDetail(
        **_summary(c).model_dump(),
        accounts=[schemas.ClusterAccount(account_id=a.account_id, role=a.role,
                                         total_in=a.total_in, total_out=a.total_out) for a in c.accounts],
        patterns=[to_pattern_out(hits[p]) for p in c.pattern_ids if p in hits],
        score_breakdown=[schemas.ScoreFactorOut(factor=f.factor, points=f.points, max_points=f.max_points,
                                                reason=f.reason) for f in c.score_breakdown],
        explanation=schemas.ExplanationOut(
            headline=e.headline, summary=e.summary, bullet_points=list(e.bullet_points),
            evidence=[schemas.EvidenceOut(transaction_id=x.transaction_id, sender=x.sender,
                                          receiver=x.receiver, amount=x.amount, timestamp=x.timestamp,
                                          note=x.note) for x in e.evidence],
            disclaimer=e.disclaimer,
        ),
        transactions=[to_transaction_out(row, r) for _, row in sub.iterrows()],
        subgraph=build_graph_out(r, account_ids=accounts, transaction_ids=ids, scope="cluster"),
    )


@router.get("/alerts", response_model=schemas.AlertList)
def alerts(level: Optional[str] = Query(None, pattern=r"^(high|medium)$")) -> schemas.AlertList:
    r = _require()
    items = [a for a in r.alerts if level is None or a.risk_level == level]
    return schemas.AlertList(items=[_alert_out(a) for a in items], total=len(items))


@router.get("/evaluation", response_model=schemas.EvaluationOut)
def evaluation() -> schemas.EvaluationOut:
    return _evaluation(_require())
